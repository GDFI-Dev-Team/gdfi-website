import fs from 'fs'

const region = JSON.parse(fs.readFileSync(new URL('./_region8.json', import.meta.url)))
const mpa = JSON.parse(fs.readFileSync(new URL('./bagonbanua.geojson', import.meta.url)))

const SAMAR = new Set(['Eastern Samar', 'Northern Samar', 'Samar'])

// Collect rings (arrays of [lon,lat]) from GeoJSON geometries.
function ringsOf(geom) {
  const out = []
  if (geom.type === 'Polygon') out.push(...geom.coordinates)
  else if (geom.type === 'MultiPolygon') geom.coordinates.forEach((p) => out.push(...p))
  return out
}

// Island = the three Samar provinces (outer rings). Rendered as one grey fill,
// so internal province borders vanish (no strokes).
const islandRings = []
for (const f of region.features) {
  if (!SAMAR.has(f.properties.adm2_en)) continue
  for (const r of ringsOf(f.geometry)) islandRings.push(r)
}
const mpaRings = ringsOf(mpa.features[0].geometry)

// --- projection: equirectangular with cos(lat0) x-correction ---
const allLons = []
const allLats = []
for (const r of [...islandRings, ...mpaRings]) for (const [lon, lat] of r) { allLons.push(lon); allLats.push(lat) }
const lat0 = (Math.min(...allLats) + Math.max(...allLats)) / 2
const k = Math.cos((lat0 * Math.PI) / 180)
const project = ([lon, lat]) => [lon * k, -lat] // y flipped for screen space

// Fit island bounds to a 1000-wide viewBox (island defines the frame).
const islandPts = islandRings.flat().map(project)
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity
for (const [x, y] of islandPts) { minX = Math.min(minX, x); minY = Math.min(minY, y); maxX = Math.max(maxX, x); maxY = Math.max(maxY, y) }
const PAD = 0.06
const spanX = maxX - minX, spanY = maxY - minY
const W = 1000
const scale = W / spanX
const H = Math.round(spanY * scale)
const offX = minX, offY = minY
const to = ([x, y]) => [ (x - offX) * scale, (y - offY) * scale ]
const toXY = (pt) => to(project(pt))

// area of a projected ring (shoelace, in viewBox units)
function area(ring) {
  const pts = ring.map(toXY)
  let a = 0
  for (let i = 0; i < pts.length; i++) {
    const [x1, y1] = pts[i]
    const [x2, y2] = pts[(i + 1) % pts.length]
    a += x1 * y2 - x2 * y1
  }
  return Math.abs(a) / 2
}

const round = (n) => Math.round(n * 10) / 10 // 0.1 unit precision

// Ramer–Douglas–Peucker in viewBox space (tolerance in viewBox units).
function rdp(pts, eps) {
  if (pts.length < 3) return pts
  let idx = 0, dmax = 0
  const [ax, ay] = pts[0]
  const [bx, by] = pts[pts.length - 1]
  const dx = bx - ax, dy = by - ay
  const len = Math.hypot(dx, dy) || 1
  for (let i = 1; i < pts.length - 1; i++) {
    const [px, py] = pts[i]
    const d = Math.abs((px - ax) * dy - (py - ay) * dx) / len
    if (d > dmax) { dmax = d; idx = i }
  }
  if (dmax > eps) {
    const left = rdp(pts.slice(0, idx + 1), eps)
    const right = rdp(pts.slice(idx), eps)
    return left.slice(0, -1).concat(right)
  }
  return [pts[0], pts[pts.length - 1]]
}

// RDP for a CLOSED ring: drop the duplicate close, split at the vertex farthest
// from pts[0] into two open chains, simplify each, then recombine.
function simplifyRing(pts, eps) {
  let p = pts.slice()
  if (p.length > 1 && p[0][0] === p[p.length - 1][0] && p[0][1] === p[p.length - 1][1]) p.pop()
  if (p.length < 4) return pts
  let far = 0, dmax = -1
  const [x0, y0] = p[0]
  for (let i = 1; i < p.length; i++) {
    const d = Math.hypot(p[i][0] - x0, p[i][1] - y0)
    if (d > dmax) { dmax = d; far = i }
  }
  const a = rdp(p.slice(0, far + 1), eps)
  const b = rdp(p.slice(far).concat([p[0]]), eps)
  return a.slice(0, -1).concat(b.slice(0, -1))
}

function pathOf(rings, minArea = 0, eps = 0) {
  let d = ''
  for (const ring of rings) {
    if (minArea && area(ring) < minArea) continue
    let pts = ring.map(toXY)
    if (eps) pts = simplifyRing(pts, eps)
    if (pts.length < 3) continue
    d += 'M' + pts.map(([x, y]) => `${round(x)} ${round(y)}`).join('L') + 'Z'
  }
  return d
}

// Drop tiny specks (< 0.03% of the whole frame) to keep the silhouette clean.
const frameArea = W * H
const islandPath = pathOf(islandRings, frameArea * 0.0003, 0.6)
const mpaPath = pathOf(mpaRings) // keep full MPA detail — it's the focal shape

// MPA bbox in viewBox space → zoom target.
const mpaPts = mpaRings.flat().map(toXY)
let mnx = Infinity, mny = Infinity, mxx = -Infinity, mxy = -Infinity
for (const [x, y] of mpaPts) { mnx = Math.min(mnx, x); mny = Math.min(mny, y); mxx = Math.max(mxx, x); mxy = Math.max(mxy, y) }
const mpa_cx = round((mnx + mxx) / 2)
const mpa_cy = round((mny + mxy) / 2)
const mpaW = mxx - mnx, mpaH = mxy - mny

const ts = `// AUTO-GENERATED by public/mpa/_gen.mjs — do not edit by hand.
// Source: Bagonbanua MPA shapefile (public/mpa/BagonBanua Shapefile) +
// Samar island (Eastern/Northern/Samar provinces, faeldon/philippines-json-maps 2023).
// Projected (equirectangular, cos-lat corrected) into a ${W}×${H} viewBox.

export const VIEW = { w: ${W}, h: ${H} } as const

/** Full Samar island silhouette — one grey fill, no strokes. */
export const ISLAND_PATH =
  '${islandPath}'

/** Bagonbanua MPA boundary polygon (from the client shapefile). */
export const MPA_PATH =
  '${mpaPath}'

/** MPA centre in viewBox units (marker + zoom focus). */
export const MPA_CENTER = { x: ${mpa_cx}, y: ${mpa_cy} } as const

/** MPA size in viewBox units (tiny at island scale). */
export const MPA_SIZE = { w: ${round(mpaW)}, h: ${round(mpaH)} } as const
`

fs.writeFileSync(new URL('../../src/features/marine-protected-areas/data/geo.ts', import.meta.url), ts)
